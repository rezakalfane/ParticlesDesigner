const text = (process.argv[2] ?? "ABSOLUMONT").toUpperCase();
const spacing = Number(process.argv[3] ?? 4); // grid units between letters
const advance = 10 + spacing;

// Chain segments that continue from the previous end point into one subpath.
let d = "";
let pen = null;
[...text].forEach((char, i) => {
  const x0 = i * advance;
  for (const [[ax, ay], [bx, by]] of GLYPHS[char] ?? []) {
    const from = `${x0 + ax},${ay}`;
    if (from !== pen) d += `M${from}`;
    pen = `${x0 + bx},${by}`;
    d += `L${pen}`;
  }
});

// Pad by one unit so round caps and the glow are not clipped.
const width = text.length * advance - spacing;
const label = text.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase());
console.log(
  `<svg class="vectrex" viewBox="-1 -1 ${width + 2} 12" role="img" aria-label="${label}">` +
    `<path d="${d}" /></svg>`,
);
